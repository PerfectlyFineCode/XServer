using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Diagnostics;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;


namespace CrossServer.PacketGenerator;

[Generator]
public class SourceGeneratorWithAttributes : IIncrementalGenerator
{
	public static Dictionary<SpecialType, string> TypeDeserializationMapping = new()
	{
		{ SpecialType.System_Boolean, "ReadBool" },
		{ SpecialType.System_Int32, "ReadInt" },
		{ SpecialType.System_String, "ReadString" },
		{ SpecialType.System_UInt32, "ReadUInt" },
		{ SpecialType.System_UInt64, "ReadULong" },
		{ SpecialType.System_Char, "ReadChar" },
		{ SpecialType.System_Single, "ReadFloat" },
		{ SpecialType.System_Double, "ReadDouble" },
		{ SpecialType.System_Decimal, "ReadDecimal" },
		{ SpecialType.System_Int64, "ReadInt64" },
		{ SpecialType.System_SByte, "ReadSByte" },
		{ SpecialType.System_Int16, "ReadShort" },
		{ SpecialType.System_UInt16, "ReadUShort" },
		{ SpecialType.System_Byte, "ReadByte" },
		{ SpecialType.System_Array, "ReadBytes" }
	};
	
	public static Dictionary<SpecialType, string> TypeSerializationMapping = new()
	{
		{ SpecialType.System_Boolean, "Write" },
		{ SpecialType.System_Int32, "Write" },
		{ SpecialType.System_String, "WriteString" },
		{ SpecialType.System_UInt32, "Write" },
		{ SpecialType.System_UInt64, "Write" },
		{ SpecialType.System_Char, "Write" },
		{ SpecialType.System_Single, "Write" },
		{ SpecialType.System_Double, "Write" },
		{ SpecialType.System_Decimal, "Write" },
		{ SpecialType.System_Int64, "Write" },
		{ SpecialType.System_SByte, "Write" },
		{ SpecialType.System_Int16, "Write" },
		{ SpecialType.System_UInt16, "Write" },
		{ SpecialType.System_Byte, "Write" },
		{ SpecialType.System_Array, "WriteBytes" }
	};
	
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var packetSymbols = context.SyntaxProvider
			.CreateSyntaxProvider(
				static (s, _) => s is StructDeclarationSyntax,
				static (ctx, _) => GetPacketSymbol(ctx))
			.Where(static symbol => symbol != null);

		context.RegisterSourceOutput(packetSymbols, GeneratePacketMethods);
	}

	private static INamedTypeSymbol? GetPacketSymbol(GeneratorSyntaxContext context)
	{
		var structDeclaration = (StructDeclarationSyntax)context.Node;

		bool isPartial = structDeclaration.Modifiers.Any(m => m.IsKind(Microsoft.CodeAnalysis.CSharp.SyntaxKind.PartialKeyword));
		if (!isPartial)
			return null;

		if (context.SemanticModel.GetDeclaredSymbol(structDeclaration) is not INamedTypeSymbol symbol)
			return null;

		var handlesPacket = symbol.AllInterfaces.Any(i => i.Name == "IPacket");
    
		return handlesPacket ? symbol : null;
	}

	private static void GeneratePacketMethods(SourceProductionContext context, INamedTypeSymbol? symbol)
	{
		if (symbol is null) return;
		
 		var namespaceName = symbol.ContainingNamespace.ToDisplayString();
		var structName = symbol.Name;
		var properties = symbol.GetMembers()
			.OfType<IPropertySymbol>()
			.Where(p => !p.IsStatic);
		
		IEnumerable<IPropertySymbol> propertySymbols = properties as IPropertySymbol[] ?? properties.ToArray();

		var sb = new StringBuilder();
		sb.AppendLine("// <auto-generated/>");
		sb.AppendLine($"namespace {namespaceName};");
		sb.AppendLine($"public partial struct {structName} : CrossServer.Shared.IPacket");
		sb.AppendLine("{");

		if (symbol.GetMembers().OfType<IMethodSymbol>().All(x => x.Name != "Serialize"))
		{
			sb.AppendLine("    public void Serialize(CrossServer.Shared.PacketWriter writer)");
			sb.AppendLine("    {");
			
			foreach (IPropertySymbol? prop in propertySymbols)
			{
				if (prop.Type.TypeKind == TypeKind.Enum)
				{
					sb.AppendLine($"        writer.Write((byte)(object){prop.Name});");
				}
				
				if (prop.Type is IArrayTypeSymbol { ElementType.SpecialType: SpecialType.System_Byte })
				{
					sb.AppendLine($"        writer.WriteBytesWithVarLength({prop.Name});");
				}
				
				if (TypeSerializationMapping.TryGetValue(prop.Type.SpecialType, out var method))
				{
					sb.AppendLine($"        writer.{method}({prop.Name});");
				}
			}
			sb.AppendLine("    }");
		}

		if (symbol.GetMembers().OfType<IMethodSymbol>().All(x => x.Name != "Deserialize"))
		{
			sb.AppendLine("    public void Deserialize(ref CrossServer.Shared.PacketReader reader)");
			sb.AppendLine("    {");
			foreach (IPropertySymbol? prop in propertySymbols)
			{
				if (prop.Type.TypeKind == TypeKind.Enum)
				{
					sb.AppendLine($"        {prop.Name} = ({prop.Type.Name})reader.ReadByte();");
					sb.AppendLine($"        if (!System.Enum.IsDefined(typeof({prop.Type.Name}), {prop.Name}))");
					sb.AppendLine("        {");
					sb.AppendLine($"            throw new System.InvalidOperationException($\"Invalid {prop.Type.Name}: {{{prop.Name}}}\");");
					sb.AppendLine("        }");
				}
				
				if (prop.Type is IArrayTypeSymbol { ElementType.SpecialType: SpecialType.System_Byte })
				{
					sb.AppendLine($"        {prop.Name} = reader.ReadBytesVarLength();");
				}
				
				if (TypeDeserializationMapping.TryGetValue(prop.Type.SpecialType, out var method))
				{
					sb.AppendLine($"        {prop.Name} = reader.{method}();");
				}
			}
			sb.AppendLine("    }");
		}


		sb.AppendLine("}");

		context.AddSource($"{structName}.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
	}
}