using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace CrossServer.PacketGenerator;

[Generator]
public sealed class PacketFactoryGenerator : IIncrementalGenerator
{
    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var provider = context.CompilationProvider.Select((compilation, _) => 
        {
            var iPacketSymbol = compilation.GetTypeByMetadataName("CrossServer.Shared.IPacket");
            if (iPacketSymbol == null) return ImmutableArray<(byte, string)>.Empty;

            var results = new List<(byte, string)>();
        
            var allTypes = GetAllTypes(compilation.GlobalNamespace);
        
            foreach (var type in allTypes)
            {
                if (type.AllInterfaces.Any(i => SymbolEqualityComparer.Default.Equals(i, iPacketSymbol)))
                {
                    var attr = type.GetAttributes().FirstOrDefault(a => a.AttributeClass?.Name == "PacketIdAttribute");
                    if (attr != null && attr.ConstructorArguments.Length > 0)
                    {
                        byte id = (byte)attr.ConstructorArguments[0].Value!;
                        results.Add((id, type.ToDisplayString()));
                    }
                }
            }
            return results.ToImmutableArray();
        });
        
        context.RegisterSourceOutput(provider, GeneratePacketFactory);
    }
    
    private static IEnumerable<INamedTypeSymbol> GetAllTypes(INamespaceSymbol ns)
    {
        foreach (var type in ns.GetTypeMembers()) yield return type;
        foreach (var childNs in ns.GetNamespaceMembers())
        {
            foreach (var type in GetAllTypes(childNs)) yield return type;
        }
    }

    private static void GeneratePacketFactory(SourceProductionContext context, ImmutableArray<(byte Id, string FullName)> packets)
    {
        StringBuilder sb = new();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("namespace CrossServer.Packets;"); 
        sb.AppendLine("using CrossServer.Shared;");
        sb.AppendLine("using CrossServer.Shared.Interfaces;");
    
        sb.AppendLine("public class GeneratedPacketProvider : IPacketProvider");
        sb.AppendLine("{");
        sb.AppendLine("    public IPacket CreatePacket(byte id) => id switch");
        sb.AppendLine("    {");

        foreach (var packet in packets.OrderBy(p => p.Id))
        {
            sb.AppendLine($"        {packet.Id} => new {packet.FullName}(),");
        }

        sb.AppendLine("        _ => throw new System.ArgumentException($\"Unknown Packet ID {id}\")");
        sb.AppendLine("    };");
        sb.AppendLine("}");

        context.AddSource("GeneratedPacketProvider.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }
}